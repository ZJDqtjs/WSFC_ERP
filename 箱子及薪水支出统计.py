# 生效中的映射（默认 = 内部硬编码；main() 会尝试用参考表覆盖）
ACTIVE_BOX_PRICES = BOX_PRICES
ACTIVE_CATEGORY_CONFIG = CATEGORY_CONFIG
ACTIVE_SPECIAL_CONFIG = SPECIAL_CONFIG
ACTIVE_SOURCE = "内部映射规则"  # 描述映射来源（用于打印）

# ===================================================================
# 智能匹配函数 resolve_category(cat)：输出 {纸箱型号, 价格, 工人单价, 箱单比, 备注, 命中类型}
# ===================================================================
# 纸箱型号末尾的 *N：如 "6号*2" -> ("6号", 2)
_BOX_STAR = re.compile(r'^(.*)\*(\d+)$')


def _lookup_box_price(box):
    """查纸箱单价。

    参考表惯例：价格按「纸箱型号」的【基础箱】单价计。
    - 直接命中（含组合箱已单独定价，如 4号+7号） -> 直接用
    - 形如 "6号*2" 表示 2 个 6号 箱体 -> 返回基础箱 6号 的单价（不 ×2）
    """
    if not box:
        return None
    if box in ACTIVE_BOX_PRICES:
        return ACTIVE_BOX_PRICES[box]
    m = _BOX_STAR.match(box)
    if m:
        base = m.group(1)
        if base in ACTIVE_BOX_PRICES:
            return ACTIVE_BOX_PRICES[base]
    return None


def resolve_category(cat):
    """智能解析一个品类名，返回完整配置字典。"""
    name = str(cat).strip()
    cfg = {
        "纸箱型号": None,
        "价格": None,
        "工人单价": None,
        "箱单比": 1,
        "备注": None,
        "_hit": False,
    }

    # 阶段 1：查 ACTIVE_SPECIAL_CONFIG
    if name in ACTIVE_SPECIAL_CONFIG:
        sp = ACTIVE_SPECIAL_CONFIG[name]
        cfg["纸箱型号"] = sp.get("纸箱型号")
        cfg["工人单价"] = sp.get("工人单价")
        r = sp.get("箱单比")
        if r is not None and r != 1:
            cfg["箱单比"] = r
        if sp.get("备注"):
            cfg["备注"] = sp.get("备注")
        cfg["_hit"] = True

    # 阶段 2：查 ACTIVE_CATEGORY_CONFIG
    if name in ACTIVE_CATEGORY_CONFIG:
        cc = ACTIVE_CATEGORY_CONFIG[name]
        if cfg["纸箱型号"] in (None, '') and cc.get("纸箱型号"):
            cfg["纸箱型号"] = cc["纸箱型号"]
        if cfg["工人单价"] in (None, 0) and cc.get("工人单价") not in (None, 0):
            cfg["工人单价"] = cc["工人单价"]
        cc_ratio = cc.get("箱单比", 1)
        if cc_ratio != 1 and cfg["箱单比"] == 1:
            cfg["箱单比"] = cc_ratio
        if not cfg["备注"] and cc.get("备注"):
            cfg["备注"] = cc["备注"]
        cfg["_hit"] = True

    # 阶段 3：纸箱数量倍率 = 纸箱型号里的 *N（如 "6号*2" -> 2；"4号" -> 1）
    #         按参考表惯例，纸箱数量 = 单量 × 纸箱型号倍率，与品名里的 *N 无关
    box = cfg["纸箱型号"]
    if box:
        bm = _BOX_STAR.match(box)
        if bm:
            cfg["箱单比"] = int(bm.group(2))

    # 阶段 4：价格 = ACTIVE_BOX_PRICES[纸箱型号]（若映射了纸箱型号）
    if cfg["纸箱型号"]:
        cfg["价格"] = _lookup_box_price(cfg["纸箱型号"])

    return cfg


