def _find_source_file():
    """自动在当前目录查找本月源表（文件名含「需求统计」的 xlsx）。"""
    cands = sorted(HERE.glob('*需求统计*.xlsx'))
    if not cands:
        raise FileNotFoundError(
            f'未在当前目录找到本月源表（文件名应包含「需求统计」）：{HERE}')
    # 副本/下载文件常带 "(N)" / "（N）" 后缀，优先排除，取主表
    def score(c):
        name = c.name
        s = 0
        if '统计核对表' in name:
            s += 2
        if '(' not in name and '（' not in name:
            s += 1  # 无副本后缀优先
        return s
    return max(cands, key=score)


def _parse_month_num(name: str) -> int:
    """从文件名解析月份数字（支持 7月 / 07月 / 七月）。解析失败返回 None。"""
    # 阿拉伯数字：如 "7月"、"12月"
    import re as _re
    m = _re.search(r'(0?[1-9]|1[0-2])月', name)
    if m:
        return int(m.group(1))
    # 中文月份名：如 "七月"
    for cn, num in _CN_TO_NUM.items():
        if cn in name:
            return num
    return None


